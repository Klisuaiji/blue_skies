   public static final Lazy<List<Item>> SPAWN_EGGS = Lazy.of(
      () -> BuiltInRegistries.ITEM
         .stream()
         .filter(
            item -> BuiltInRegistries.ITEM.getKey(item).getNamespace().equals("blue_skies")
               && item instanceof SpawnEggItem
               && !(item instanceof BossSpawnEggItem)
         )
         .sorted((o, n) -> BuiltInRegistries.ITEM.getKey(o).compareTo(BuiltInRegistries.ITEM.getKey(n)))
         .collect(Collectors.toList())
   );

   @SubscribeEvent
   public static void modifyExisting(BuildCreativeModeTabContentsEvent event) {
      if (event.getTabKey().equals(CreativeModeTabs.SPAWN_EGGS)) {
         for (Item item : (List)SPAWN_EGGS.get()) {
            event.accept(item);
         }
      }
   }

