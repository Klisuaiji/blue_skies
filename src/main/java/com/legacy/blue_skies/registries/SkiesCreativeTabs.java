   protected static void insertAfter(MutableHashedLinkedMap<ItemStack, TabVisibility> entries, List<ItemLike> items, ItemLike target) {
      ItemStack currentStack = null;

      for (Entry<ItemStack, TabVisibility> e : entries) {
         if (e.getKey().getItem() == target) {
            currentStack = e.getKey();
            break;
         }
      }

      for (ItemLike item : items) {
         entries.putAfter(currentStack, currentStack = item.asItem().getDefaultInstance(), TabVisibility.PARENT_AND_SEARCH_TABS);
      }
   }

   protected static void printMissingItems(BuildCreativeModeTabContentsEvent event) {
      try {
         Set<Item> items = new HashSet<>();

         for (Entry<ItemStack, TabVisibility> e : event.getEntries()) {
            items.add(e.getKey().getItem());
         }

         for (Item e : BuiltInRegistries.ITEM
            .stream()
            .filter(block -> BuiltInRegistries.ITEM.getKey(block).getNamespace().equals("blue_skies") && !items.contains(block))
            .collect(Collectors.toList())) {
            System.out.println(BuiltInRegistries.ITEM.getKey(e));
         }
      } catch (Exception var5) {
         var5.printStackTrace();
      }
   }
